/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_CAN_Init();
  MX_I2C1_Init();
  MX_TIM2_Init();
  MX_TIM17_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */
  MX_CAN_Init();  // inicjalizacja magistrali CAN z nowym adresem

  /*Odbior danych w przerwaniu*/
   HAL_UARTEx_ReceiveToIdle_IT(&huart2, RXData, 9);

   TXData[0] = 0x01;  //Adres slave'a, czyli naszego czujnika
   TXData[1] = 0x03;  // Kod funkcji ->0x03 (odczyt rejestrow)

   /*Adres poczatkowy odczytywanego rejestru*/
   TXData[2] = 0x00;
   TXData[3] = 0x00;

   /*Ilosc rejestrow, ktore chcemy odczytac -> tutaj 2 rejestry,
 	czyli temperatura i wilgotnosc */
   TXData[4] = 0x00;
   TXData[5] = 0x02;

   /*Obliczanie CRC*/
   uint16_t crc = crc16(TXData, 6);
   TXData[6] = crc&0xFF;   // CRC LOW
   TXData[7] = (crc>>8)&0xFF;  // CRC HIGH
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */

  while (1) {
    if (NPK_EN == 1)
    {
    HAL_UART_Transmit(&huart2, TXData, 8, 1000);
    }
    HAL_Delay(1000);
    CAN_Transmit_NPK_EN();
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

