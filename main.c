uint8_t RXData[9];
uint8_t TXData[8];
int16_t humidity;
int16_t temperature;

void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size)
{
	if (RXData[0] == 0x01 && RXData[1] ==0x03 && RXData[2] ==0x04)
	{
		humidity = RXData[3]*256 + RXData[4];
		temperature = RXData[5]*256 + RXData[6];
		CAN_Transmit_Data(temperature, humidity);
	}
	HAL_UARTEx_ReceiveToIdle_IT(&huart2, RXData, 9);

}

